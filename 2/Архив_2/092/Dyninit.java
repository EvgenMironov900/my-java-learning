class Dyninit {
  public static void main(String[] args) {
  double а = 3.0, Ь = 4.0;
// Переменная с инициализируется динамически .
  double с = Math.sqrt(а * а + Ь * Ь);
  System.out.println("Длина гипотенузы равна " + с ) ;
  }
}

