class IncDec {
  public static void main(String[] args) {
    int а = 1;
    int b = 2;
    int с;
    int d;
    с = ++b;
    d = а++;
    с++;
    System.out.println("a = " + а);
    System.out.println("b = " + b);
    System.out.println("c = " + с);
    System.out.println("d = " + d);
  }
}

